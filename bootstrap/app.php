<?php

use App\Http\Middleware\EncryptCookies;
use App\Http\Middleware\SetTenantSessionConfig;
use Illuminate\Console\Scheduling\Schedule;
use Illuminate\Cookie\Middleware\EncryptCookies as BaseEncryptCookies;
use Illuminate\Foundation\Application;
use Illuminate\Foundation\Configuration\Exceptions;
use Illuminate\Foundation\Configuration\Middleware;
use Illuminate\Foundation\Http\Middleware\ConvertEmptyStringsToNull;
use Illuminate\Foundation\Http\Middleware\PreventRequestsDuringMaintenance;
use Webkul\Core\Http\Middleware\SecureHeaders;
use Webkul\Installer\Http\Middleware\CanInstall;
return Application::configure(basePath: dirname(__DIR__))
    ->withRouting(
        web: __DIR__.'/../routes/web.php',
        api: __DIR__.'/../routes/api.php',
        commands: __DIR__.'/../routes/console.php',
        health: '/up',
    )
    ->withMiddleware(function (Middleware $middleware) {
        // MOVE THIS TO THE TOP: Global middleware runs before Group middleware
        $middleware->use([
            \App\Http\Middleware\InitializeTenancyForSubdomains::class,
            \App\Http\Middleware\SetTenantSessionConfig::class,
            \App\Http\Middleware\SetTenantStorageDisk::class,
            \App\Http\Middleware\TenantAdminSecurity::class,
        ]);

        $middleware->alias([
            'pos-auth'         => \Webkul\Pos\Http\Middleware\Pos::class,
            'superadmin.perm'  => \App\Http\Middleware\SuperAdminPermission::class,
            'superadmin.guard' => \App\Http\Middleware\SuperAdminSessionGuard::class,
        ]);

        // Clean up the web group
        $middleware->group('web', [
            \Illuminate\Cookie\Middleware\EncryptCookies::class,
            \Illuminate\Cookie\Middleware\AddQueuedCookiesToResponse::class,
            \Illuminate\Session\Middleware\StartSession::class,
            \Illuminate\View\Middleware\ShareErrorsFromSession::class,
            \Illuminate\Foundation\Http\Middleware\ValidateCsrfToken::class,
            \Illuminate\Routing\Middleware\SubstituteBindings::class,
            \App\Http\Middleware\SetUserLanguage::class,
            \App\Http\Middleware\ImpersonationBanner::class,
            \App\Http\Middleware\PlatformAnnouncementBanner::class,
        ]);

        $middleware->trustProxies('*');

        $middleware->validateCsrfTokens(except: [
            'admin/catalog/waste',
            'admin/catalog/waste/*',
            'admin/inventory/reorder',
            'admin/inventory/reorder/*',

            // Customer display: JWT-authed (auth:pos) or token-credentialed
            // (the pairing_token IS the secret). No session, so no CSRF.
            'pos/api/customer-display/*',
            'pos/display/*/ping',
        ]);

        // Stop unauthenticated API calls from crashing on `route('login')`.
        // For /api/* requests Laravel must respond with JSON 401, not redirect.
        $middleware->redirectGuestsTo(function (\Illuminate\Http\Request $request) {
            if ($request->expectsJson() || $request->is('api/*')) {
                return null; // Authenticate will throw an AuthenticationException → JSON 401
            }
            // Note: in practice the actual redirect for /superadmin/* is
            // generated by App\Exceptions\Handler::register() because Webkul's
            // RestApi handler intercepts AuthenticationException and ignores
            // this callback. We still set this for completeness — it's the
            // path Laravel takes when no renderable matches.
            if (str_starts_with(ltrim($request->path(), '/'), 'superadmin')) {
                return route('superadmin.login');
            }
            return route('shop.customer.session.create');
        });
    })


    ->withSchedule(function (Schedule $schedule) {
        // login_tokens lives in tenant DBs, so prune via tenants:run
        $schedule->command('tenants:run', ['login-tokens:prune'])
            ->daily()
            ->onOneServer()
            ->name('prune-login-tokens')
            ->withoutOverlapping();

        // pos_customer_display_sessions lives in tenant DBs.
        $schedule->command('tenants:run', ['pos:customer-displays:revoke-expired'])
            ->everyFifteenMinutes()
            ->onOneServer()
            ->name('revoke-expired-customer-displays')
            ->withoutOverlapping();

        // === TikTok Shop schedules ===
        // Per master prompt §6: each closure sweeps tenants via chunkById(50)
        // and dispatches one job per tenant. NEVER iterate tenants inside a
        // single job — one slow/throwing tenant must not block others.

        $schedule->call(function () {
            \App\Models\Tenant::query()->chunkById(50, function ($tenants) {
                $tenants->each(fn ($t) => \Fujiba\TikTokShop\Jobs\SyncProductsToTikTok::dispatch((string) $t->id)->onQueue('tiktok'));
            });
        })->dailyAt('02:00')->name('tiktok-sync-products')->withoutOverlapping();

        $schedule->call(function () {
            \App\Models\Tenant::query()->chunkById(50, function ($tenants) {
                $tenants->each(fn ($t) => \Fujiba\TikTokShop\Jobs\ImportTikTokOrders::dispatch((string) $t->id)->onQueue('tiktok'));
            });
        })->everyFifteenMinutes()->name('tiktok-import-orders')->withoutOverlapping();

        $schedule->call(function () {
            \App\Models\Tenant::query()->chunkById(50, function ($tenants) {
                $tenants->each(fn ($t) => \Fujiba\TikTokShop\Jobs\RefreshTikTokTokens::dispatch((string) $t->id)->onQueue('tiktok'));
            });
        })->everyThirtyMinutes()->name('tiktok-refresh-tokens')->withoutOverlapping();

        // SSL auto-renew: daily refresh of cert status + renew anything < 30 days to expiry.
        // Runs in central context (no tenants:run wrapper) since it walks the
        // tenants table itself. SslService is a no-op when sudoers isn't set up.
        $schedule->command('ssl:auto-renew')
            ->dailyAt('03:30')
            ->onOneServer()
            ->name('ssl-auto-renew')
            ->withoutOverlapping();

        // Inventory index drifts when stock is written outside the catalog event
        // path (ChatPion sync, Clone Tenant, Sagawa returns, manual SQL). Stale
        // index → product_inventory_indices.qty=0 → is_saleable=false → add-to-cart
        // disabled even though product_inventories.qty>0. Recompute hourly per
        // tenant. tenants:run --option marshals --type=* poorly, so iterate via
        // closure and call reindexFull() directly.
        $schedule->call(function () {
            \App\Models\Tenant::query()->chunkById(50, function ($tenants) {
                $tenants->each(function ($tenant) {
                    tenancy()->initialize($tenant);
                    try {
                        app(\Webkul\Product\Helpers\Indexers\Inventory::class)->reindexFull();
                    } finally {
                        tenancy()->end();
                    }
                });
            });
        })->hourly()->name('reindex-inventory')->onOneServer()->withoutOverlapping();
    })
    ->withExceptions(function (Exceptions $exceptions) {
        // Super-admin AuthenticationException routing is handled by
        // App\Exceptions\Handler, which extends Webkul/RestApi's handler and
        // is bound in AppServiceProvider::boot() so it overrides upstream
        // bindings.
    })->create();
