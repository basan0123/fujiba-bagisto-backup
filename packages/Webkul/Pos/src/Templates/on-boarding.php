  Welcome to the <info>Bagisto POS</info> project!
  Bagisto Pos Extension is a perfect solution for management of a physical store.

  Key Features:
    - ⭐ Creation of multiple outlets from back-end.
    - ⭐ Cart Hold feature is available from front-end.
    - ⭐ Barcode generate and print features available at back-end.
    - ⭐ Admin can manage the inventory separately for each outlets.
    - ⭐ Real Time Sync (customers and orders in offline mode).
    - ⭐ Option to customize Pos sales invoice.
